"""Generate assets/css/pdh-tgh-colors.css: TGH's homepage section styles in PDH colours.

Copies every rule from assets/css/global.css whose selector belongs to the TGH homepage sections we use
(quick links + image CTAs, "Why PDH" tiles, "Here for You", service blurbs, news), keeps only the
declarations that use TGH's palette, and swaps each colour for its PDH equivalent. Layout, spacing and
animation stay TGH's; only colour changes. Loaded after global.css, so the same selectors win by order.

Run after replacing or updating global.css:  python tools/recolor_tgh_sections.py
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "assets", "css", "global.css")
OUT = os.path.join(ROOT, "assets", "css", "pdh-tgh-colors.css")

SECTIONS = (".cta-list-teasers", ".banner-cta", ".image-cta", ".featured-content-awards", ".image-with-ctas",
            ".blurb_section", ".blurb", ".related-content")

# TGH colour -> PDH colour (rgb triples, so hex and rgba() forms both map).
PALETTE = {
    (0x22, 0x31, 0x3f): (0x0d, 0x3b, 0x40),  # navy      -> PDH deep teal
    (0x60, 0xd1, 0xe0): (0x4c, 0xc9, 0xc6),  # cyan      -> PDH aqua
    (0xff, 0xe5, 0x4f): (0xf4, 0x7a, 0x20),  # yellow    -> PDH orange
    (0xdb, 0xe4, 0x42): (0xff, 0x9a, 0x4d),  # lime      -> light orange
    (0x00, 0x8e, 0xaa): (0x00, 0x7f, 0x86),  # link blue -> PDH teal
}
HEX = {"#%02x%02x%02x" % k: "#%02x%02x%02x" % v for k, v in PALETTE.items()}
RGB = {"%d,%d,%d" % k: "%d,%d,%d" % v for k, v in PALETTE.items()}

HEX_RE = re.compile(r"#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b")
RGBA_RE = re.compile(r"rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)")


def full_hex(h):
    h = h.lower()
    return "#" + "".join(c * 2 for c in h[1:]) if len(h) == 4 else h


def recolor(value):
    """Return (new_value, changed)."""
    changed = False

    def hx(m):
        nonlocal changed
        h = full_hex(m.group(0))
        if h in HEX:
            changed = True
            return HEX[h]
        return m.group(0)

    def rg(m):
        nonlocal changed
        key = "%s,%s,%s" % m.groups()
        if key in RGB:
            changed = True
            return m.group(0)[: m.group(0).index("(") + 1] + RGB[key]
        return m.group(0)

    value = HEX_RE.sub(hx, value)
    value = RGBA_RE.sub(rg, value)
    return value, changed


def rules(css):
    """Yield (at_rule_prefixes, selector, body) for every style rule, descending into @media/@supports."""
    def walk(text, at):
        i = 0
        while i < len(text):
            brace = text.find("{", i)
            if brace == -1:
                return
            head = text[i:brace].strip()
            depth, j = 1, brace + 1
            while depth and j < len(text):
                if text[j] == "{":
                    depth += 1
                elif text[j] == "}":
                    depth -= 1
                j += 1
            body = text[brace + 1 : j - 1]
            if head.startswith("@media") or head.startswith("@supports"):
                yield from walk(body, at + [head])
            elif not head.startswith("@"):
                yield at, head, body
            i = j

    yield from walk(re.sub(r"/\*.*?\*/", "", css, flags=re.S), [])


def main():
    css = open(SRC, encoding="utf-8").read()
    out, count = [], 0
    for at, selector, body in rules(css):
        parts = [s.strip() for s in selector.split(",")]
        parts = [s for s in parts if any(c in s for c in SECTIONS)]
        if not parts:
            continue
        decls = []
        for d in body.split(";"):
            if ":" not in d:
                continue
            prop, val = d.split(":", 1)
            new, changed = recolor(val)
            if changed:
                decls.append(prop.strip() + ":" + new.strip())
        if not decls:
            continue
        rule = ",".join(parts) + "{" + ";".join(decls) + "}"
        for a in reversed(at):
            rule = a + "{" + rule + "}"
        out.append(rule)
        count += 1
    header = ("/* GENERATED by tools/recolor_tgh_sections.py from global.css: TGH homepage sections in PDH colours.\n"
              "   Do not edit by hand; re-run the tool after changing global.css. */\n")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(header + "\n".join(out) + "\n")
    print(f"Wrote {os.path.relpath(OUT, ROOT)} ({count} rules)")


if __name__ == "__main__":
    main()
